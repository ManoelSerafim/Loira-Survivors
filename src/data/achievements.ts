function metaMaxedInCategory(ctx: AchievementContext, category: 'combate' | 'viagem' | 'sorte'): number {
  return META_UPGRADES.filter(
    (upgrade) => upgrade.category === category && (ctx.save.meta[upgrade.id] ?? 0) >= upgrade.maxLevel,
  ).length;
}

const categoryCount = (category: 'combate' | 'viagem' | 'sorte') =>
  META_UPGRADES.filter((upgrade) => upgrade.category === category).length;

