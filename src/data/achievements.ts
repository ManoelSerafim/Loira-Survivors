export function achievementProgress(achievement: AchievementDef, ctx: AchievementContext) {
  if (ctx.save.achievements[achievement.id]) return { current: 1, target: 1, unlocked: true };
  const progress = achievement.progress?.(ctx);
  return progress ? { ...progress, unlocked: false } : { current: 0, target: 1, unlocked: false };
}
